"""Practice problem sets, hint ladder (R0-R5), and multimodal drawing review contracts.

Pure Pydantic models with ZERO I/O.
Follows the doctrine of commit-before-pose and cold retrieval practice.
"""

from typing import Literal

from pydantic import BaseModel, Field, field_validator

from learnharness.core.contracts.quiz import QuizPayload

HintLevel = Literal["R0", "R1", "R2", "R3", "R4", "R5"]


class HintStep(BaseModel):
    """Single rung on the pedagogical hint ladder (R0 to R5)."""
    level: HintLevel
    label: str
    prompt: str


class RubricCriterion(BaseModel):
    """Specific scoring criterion for grading student practice responses."""
    id: str
    description: str
    max_points: int = 2


class PracticeProblem(BaseModel):
    """Practice exercise requiring commit-before-pose doctrine.

    The generator subagent MUST formulate the complete solution and rubric
    BEFORE presenting the problem to the learner.
    """
    problem_id: str
    topic: str
    kind: Literal["recall", "discrimination", "composition"] = "composition"
    prompt: str
    committed_solution: str
    rubric: list[RubricCriterion] = Field(default_factory=list)
    hints: list[HintStep] = Field(default_factory=list)
    target_misconception: str = ""

    @field_validator("committed_solution")
    @classmethod
    def validate_committed_solution_non_empty(cls, value: str) -> str:
        if not value or not value.strip():
            raise ValueError(
                "committed_solution cannot be empty. Doctrine of commit-before-pose requires "
                "a reference solution before presenting the exercise."
            )
        return value


class PracticeAttemptGrade(BaseModel):
    """Evaluation of a learner's submitted attempt on a practice problem."""
    problem_id: str
    score: int = Field(ge=0, le=10)
    max_score: int = 10
    criterion_scores: dict[str, int] = Field(default_factory=dict)
    feedback: str
    next_hint: HintStep | None = None
    passed: bool = False


class PracticeSet(BaseModel):
    """Collection of practice problems generated by LangGraph pipeline or cold practice session."""
    set_id: str
    title: str
    target_topics: list[str] = Field(default_factory=list)
    problems: list[PracticeProblem] = Field(default_factory=list)
    current_hint_idx: dict[str, int] = Field(default_factory=dict)
    grades: dict[str, PracticeAttemptGrade] = Field(default_factory=dict)
    created_at: str = ""


class DrawingReviewResult(BaseModel):
    """Multimodal vision evaluation of an Excalidraw retrieval drawing (.png)."""
    slug: str
    correct_points: list[str] = Field(default_factory=list)
    missing_points: list[str] = Field(default_factory=list)
    incorrect_points: list[str] = Field(default_factory=list)
    summary_markdown: str = ""
    follow_up_quiz: QuizPayload | None = None
