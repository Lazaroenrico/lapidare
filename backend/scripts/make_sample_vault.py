#!/usr/bin/env python
"""Generate ``tests/fixtures/sample-vault/`` through the production code paths.

Run from ``backend/``:  ``uv run python scripts/make_sample_vault.py``

A scripted ``FakeEngine`` drives the real FastAPI app: vault bootstrap, one complete TEACH
session (probe -> probe_done -> plan_init -> quizzes -> plan_advance until done), one PRACTICE
session (problem / conclude), one graph extraction and one finished research job.

Determinism: before the app runs, every ``uuid4`` and ``datetime`` reference inside the
``learnharness`` modules is replaced by a counter-based uuid and a fixed, ticking clock. Nothing
in production code changes. The output is written to a temp dir and copied over the fixture
folder only when the run succeeded. Never hand-edit the result: change the script, regenerate.
"""

from __future__ import annotations

import asyncio
import importlib
import itertools
import os
import pkgutil
import shutil
import sys
import tempfile
import uuid
from datetime import UTC, date, datetime, timedelta
from pathlib import Path

BACKEND = Path(__file__).resolve().parents[1]
sys.path[:0] = [str(BACKEND), str(BACKEND / "src")]

OUT = BACKEND / "tests" / "fixtures" / "sample-vault"
CLOCK_START = datetime(2026, 1, 5, 9, 0, 0, tzinfo=UTC)
PLACEHOLDER_VAULT_PATH = "~/Documents/SampleVault"
README = """# sample-vault

Generated by `scripts/make_sample_vault.py`, never hand-edit.

A small Vault produced through the production code paths (bootstrap, TEACH and PRACTICE
sessions, graph extraction, a research job) with a scripted engine, a fixed clock and counter
based ids. `tests/integration/test_sample_vault.py` opens a copy of it with the real readers.

If a persisted format changes, run `cd backend && uv run python scripts/make_sample_vault.py`
and commit the regenerated folder in the same commit.

`.harness/langgraph.sqlite` (a disposable checkpoint with machine-specific bytes) and
the ownership lock are deliberately not part of the fixture.
"""


def install_determinism() -> None:
    """Replace uuid4/datetime in every learnharness module (and in uuid/datetime themselves)."""
    import datetime as datetime_module

    import learnharness

    for info in pkgutil.walk_packages(learnharness.__path__, "learnharness."):
        importlib.import_module(info.name)

    ticks = itertools.count()
    real_datetime = datetime

    class FixedDatetime(real_datetime):  # type: ignore[misc]
        @classmethod
        def now(cls, tz=None):
            moment = CLOCK_START + timedelta(seconds=next(ticks))
            return moment.astimezone(tz) if tz else moment.replace(tzinfo=None)

    real_date = date

    class _DateMeta(type):
        def __instancecheck__(cls, obj):
            return isinstance(obj, real_date)

        def __getattr__(cls, name):
            return getattr(real_date, name)

    class FixedDate(metaclass=_DateMeta):
        """Stand-in for ``date`` whose ``today()`` returns a real (yaml-friendly) date."""

        @staticmethod
        def today() -> date:
            return CLOCK_START.date()

    counter = itertools.count(1)

    def fixed_uuid4() -> uuid.UUID:
        # Counter in the TOP bits: ids are cut as ``hex[:12]`` and must stay distinct.
        return uuid.UUID(int=next(counter) << 80)

    datetime_module.datetime = FixedDatetime  # type: ignore[misc]
    uuid.uuid4 = fixed_uuid4
    for name, module in list(sys.modules.items()):
        if not name.startswith("learnharness"):
            continue
        if getattr(module, "uuid4", None) is not None:
            module.uuid4 = fixed_uuid4  # type: ignore[attr-defined]
        if getattr(module, "date", None) is real_date:
            module.date = FixedDate  # type: ignore[attr-defined]
        if getattr(module, "datetime", None) is real_datetime:
            module.datetime = FixedDatetime  # type: ignore[attr-defined]


async def generate(vault: Path) -> None:
    import httpx

    from learnharness.api.app import create_app
    from learnharness.api.state import AppState
    from learnharness.core.contracts.graph import AuditPayload, ExtractionPayload
    from learnharness.core.contracts.jobs import ResearchResult
    from learnharness.vault.bootstrap import bootstrap_vault, load_config, save_config
    from tests.conftest import FakeEngine, configure_vault, tool

    class SampleEngine(FakeEngine):
        """FakeEngine that can also research (scripted)."""

        def research_ready(self) -> bool:
            return True

        async def research(self, prompt, slot=None):
            return ResearchResult(
                brief="## Resumo\nO produto escalar mede alinhamento entre dois vetores.\n",
                sources=[{"title": "Dot product", "url": "https://en.wikipedia.org/wiki/Dot_product"}],
            )

    configure_vault(vault)
    config = load_config(vault)
    config.vault_path = PLACEHOLDER_VAULT_PATH
    config.graph.extraction_chunk_tokens = 1  # every finished run feeds the graph
    save_config(vault, config)
    del bootstrap_vault  # imported only to document that configure_vault uses it

    engine = SampleEngine()
    engine.program(ExtractionPayload, lambda prompt: {
        "propositions": [
            {"key": "p1", "name": "Produto Escalar",
             "statement": "O produto escalar soma os produtos coordenada a coordenada."},
            {"key": "p2", "name": "Escores de Atenção",
             "statement": "Os escores de atenção são produtos escalares entre consultas e chaves."},
        ],
        "chains": [{"premises": ["p1"], "conclusion": "p2"}],
    })
    engine.program(AuditPayload, {"links": []})
    quiz_options = [{"value": "a", "label": "11"}, {"value": "b", "label": "10"}]
    engine.script_turn(
        "## Produto Escalar\n\nDefinição: soma dos produtos coordenada a coordenada.\n",
        tool("probe_done", strands=[{"strand": "álgebra linear",
                                     "assessment": "Piso: vetores. Teto: produto escalar."}]),
        tool("plan_init", mermaid="graph TD\n  dot[Produto Escalar] --> attn[Atenção]",
             approach_prose="Primeiro o produto escalar, depois a atenção."),
        tool("research", question="O que o produto escalar mede geometricamente?",
             context="aula de atenção"),
        tool("quiz", type="check", node_id="dot", question="Quanto vale (1,2)·(3,4)?",
             options=quiz_options, explanation="1*3 + 2*4 = 11.", correct="a"),
        tool("plan_advance", node_id="dot", status="mastered"),
        "Agora a atenção: cada escore é um produto escalar.\n",
        tool("quiz", type="check", node_id="attn", question="Um escore de atenção é...",
             options=[{"value": "a", "label": "um produto escalar"}, {"value": "b", "label": "uma soma"}],
             explanation="Consulta · chave.", correct="a"),
        tool("plan_advance", node_id="attn", status="mastered"),
        "Ótimo, você dominou o plano.\n",
    )

    state = AppState(vault_path=vault, engine_factory=lambda slot: engine)
    app = create_app(state=state)

    async def _diag():
        return {"chats": (await http.get("/api/chats")).json(), "jobs": (await http.get("/api/jobs")).json(),
                "turns_left": len(engine.turns), "tool_results": engine.tool_results}

    async def until(check, timeout: float = 15.0):
        deadline = asyncio.get_running_loop().time() + timeout
        while not (value := await check()):
            if asyncio.get_running_loop().time() > deadline:
                raise TimeoutError(f"sample vault generation stalled; last check: {await _diag()}")
            await asyncio.sleep(0.02)
        return value

    async with app.router.lifespan_context(app):
        transport = httpx.ASGITransport(app=app)
        async with httpx.AsyncClient(transport=transport, base_url="http://127.0.0.1:8000") as http:
            created = await http.post("/api/chats", json={"mode": "TEACH", "topic": "Mecanismo de atenção"})
            created.raise_for_status()
            teach_id = created.json()["id"]

            answered: set[str] = set()

            async def answer_quizzes() -> None:
                while True:
                    quiz = (await http.get(f"/api/chats/{teach_id}")).json().get("pending_quiz")
                    if quiz and quiz["quiz_id"] not in answered:
                        answered.add(quiz["quiz_id"])
                        (await http.post(f"/api/chats/{teach_id}/answer", json={
                            "quiz_id": quiz["quiz_id"], "chosen_index": 0, "confidence": 85,
                        })).raise_for_status()
                    await asyncio.sleep(0.02)

            answerer = asyncio.create_task(answer_quizzes())

            async def teach_settled():
                jobs = (await http.get("/api/jobs")).json()
                kinds = {j["kind"]: j["status"] for j in jobs}
                busy = state.sessions.is_running(teach_id)
                return (not busy and kinds.get("research") == "completed"
                        and kinds.get("extraction") == "completed")

            try:
                await until(teach_settled)
            finally:
                answerer.cancel()
            await asyncio.sleep(0.2)  # let the last steer / flush settle

            engine.script_turn("Vamos ao primeiro problema.", tool(
                "problem", statement="Por que o escalar de dois vetores mede alinhamento?",
                mode="recall", model_solution="Porque cresce com o cosseno do ângulo entre eles.",
                target=["Produto Escalar"]))
            practice = await http.post("/api/chats", json={"mode": "PRACTICE", "topic": "Produto escalar"})
            practice.raise_for_status()
            practice_id = practice.json()["id"]

            async def problem_open():
                chat = (await http.get(f"/api/chats/{practice_id}")).json()
                return chat["practice"]["active_problem_id"] and not state.sessions.is_running(practice_id)

            await until(problem_open)
            engine.script_turn(
                "Isso: o cosseno entra na conta.",
                tool("conclude", outcome="solved", verdict="Reconstruiu a ideia.", rung="R2",
                     miss_class="cue", retest=False),
                "Bem feito.",
            )
            (await http.post(f"/api/chats/{practice_id}/messages", json={
                "kind": "attempt", "content": "Cresce com o cosseno do ângulo.",
            })).raise_for_status()

            async def concluded():
                chat = (await http.get(f"/api/chats/{practice_id}")).json()
                return chat["practice"]["active_problem_id"] is None and not state.sessions.is_running(practice_id)

            await until(concluded)
            await asyncio.sleep(0.2)
            assert not engine.turns, "unused scripted turns left over"


def prune(vault: Path) -> None:
    """Drop machine-specific, non-deterministic files that are not part of the fixture."""
    for path in list(vault.rglob("*")):
        if path.name.startswith("langgraph.sqlite") or path.suffix == ".lock" or path.name.endswith(".lock"):
            path.unlink(missing_ok=True)
    for path in sorted(vault.rglob("*"), reverse=True):
        if path.is_dir() and not any(path.iterdir()):
            path.rmdir()


def main() -> None:
    scratch = Path(tempfile.mkdtemp(prefix="sample-vault-"))
    try:
        os.environ["XDG_CONFIG_HOME"] = str(scratch / "xdg")
        os.environ["LEARNHARNESS_CHROMIUM"] = "off"
        for name in ("LEARNHARNESS_VAULT_PATH", "LEARNHARNESS_APP_VERSION", "LEARNHARNESS_DESKTOP_SECRET"):
            os.environ.pop(name, None)
        install_determinism()
        vault = scratch / "Vault"
        asyncio.run(generate(vault))
        prune(vault)
        if OUT.exists():
            shutil.rmtree(OUT)
        shutil.copytree(vault, OUT)
        (OUT / "README.md").write_text(README, encoding="utf-8")
        print(f"sample vault written to {OUT}")
    finally:
        shutil.rmtree(scratch, ignore_errors=True)


if __name__ == "__main__":
    main()
